import assert from 'node:assert/strict';
import fs from 'node:fs';
import {PGlite} from '@electric-sql/pglite';
import {pgcrypto} from '@electric-sql/pglite/contrib/pgcrypto';
import {_internals as rico} from '../supabase/functions/api/assistant.ts';
const search=globalThis.RicottaSearch;
const w={items:[{id:'tomato',name:'تەماتە',aliases:['Tomato','Tomatoes'],unit_id:'kg',supplier_id:'veg',available:true},{id:'lettuce',name:'خاس لولو',aliases:['French lettuce'],unit_id:'kg',supplier_id:'veg',available:true},{id:'hidden',name:'Hidden',aliases:['Banana'],available:false}],suppliers:[{id:'veg',name:'Vegetable market'}],units:[{id:'kg',en:'kg',ku:'کیلۆ'}],history:[],cart:{},now:{date:'2026-10-14',weekday:3}};
assert.equal(rico.toolFindItems(w,{query:'tomtao'}).items[0].item_id,'tomato');
assert.equal(rico.toolFindItems(w,{query:'lettuce french'}).items[0].item_id,'lettuce');
assert.equal(rico.toolFindItems(w,{query:'تةمـاتة'}).items[0].item_id,'tomato');
assert.equal(rico.toolFindItems(w,{query:'banana'}).items[0].available,false);
assert.equal(rico.toolFindItems(w,{limit:1}).next_offset,1);
assert.equal(rico.toolFindItems(w,{limit:1,offset:1}).items[0].item_id,'lettuce');
assert.equal(search.score('ham',['jam']),Infinity,'short food names must not fuzzy-match');
assert.equal(search.score('rice 25',['rice 5']),Infinity,'numbers must not fuzzy-match');
assert.ok(search.score('tomato',['Tomato'])<search.score('tomato',['Tomatillo']));
const events=[],emit=e=>events.push(e);
assert.equal(rico.proposeEditItem(w,{item_id:'tomato',aliases:['Tomato','Fresh tomato'],available:false,note:'ripe'},emit).shown,true);
assert.deepEqual(events[0].proposal.aliases,['Tomato','Fresh tomato']);
assert.equal(events[0].proposal.name,'تەماتە','aliases never rename the primary item');
events.length=0;
assert.equal(rico.proposeItemAliases(w,{items:[{item_id:'tomato',aliases:['Tomato']}]},emit).shown,true);
assert.equal(events[0].proposal.kind,'item_aliases');
assert.deepEqual(events[0].proposal.entries[0].before,['Tomato','Tomatoes']);
assert.ok(rico.proposeItemAliases(w,{items:[{item_id:'missing',aliases:['X']}]},emit).error);
events.length=0;
rico.proposeOrder(w,{lines:[{item_id:'tomato',qty:0.125},{item_id:'hidden',qty:1}]},emit,false);
assert.equal(events[0].proposal.lines.length,1);
assert.equal(events[0].proposal.lines[0].qty,0.125);
assert.ok(rico.MANUAL.includes('propose_item_aliases'));
assert.ok(rico.TOOLS.find(t=>t.name==='propose_edit_item').input_schema.properties.aliases);
const db=new PGlite({extensions:{pgcrypto}});
try{
 await db.exec('create role anon;create role authenticated;create role service_role;');
 await db.exec(fs.readFileSync('supabase/baseline.sql','utf8'));
 for(const file of fs.readdirSync('supabase/migrations').filter(f=>f.endsWith('.sql')).sort())await db.exec(fs.readFileSync('supabase/migrations/'+file,'utf8'));
 await db.exec("insert into app_units(id,en)values('kg','kg');insert into app_items(id,name,unit_id,note,available)values('a','Original','kg','Preserve me',false),('b','Second','kg',null,true);");
 const call=async entries=>(await db.query('select app_internal_set_aliases($1::jsonb,$2,$3) as result',[JSON.stringify(entries),'rozha',null])).rows[0].result;
 assert.equal((await call([{itemId:'a',before:[],aliases:['English']}])).changed,1);
 assert.equal((await call([{itemId:'a',before:[],aliases:['English']}])).changed,0,'retries are idempotent');
 assert.deepEqual((await call([{itemId:'a',before:[],aliases:['Stale']},{itemId:'b',before:[],aliases:['Second alias']}])).conflicts,['a']);
 assert.deepEqual((await db.query("select aliases from app_items where id='b'")).rows[0].aliases,[],'stale batch is atomic');
 const row=(await db.query("select name,note,available,aliases from app_items where id='a'")).rows[0];
 assert.deepEqual(row,{name:'Original',note:'Preserve me',available:false,aliases:['English']});
 assert.equal((await db.query("select has_function_privilege('anon','app_internal_set_aliases(jsonb,text,text)','EXECUTE') as ok")).rows[0].ok,false);
 assert.equal((await db.query("select count(*)::int as n from app_audit_events where entity_name='Original'")).rows[0].n,1,'server audit records successful alias changes once');
 await assert.rejects(call([{itemId:'a',before:['English'],aliases:[1]}]),/Invalid alias/);
}finally{await db.close();}
console.log('Rico/search PASS: aliases, typos, multi-word search, fractions, availability, proposal previews, atomic/stale-safe alias updates and permissions');
